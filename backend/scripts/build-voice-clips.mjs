// Bundles the voice-over clips in the repo root into public/voice-clips.js so
// the iMessage simulator can play them even when opened straight from disk,
// where fetch() of neighbouring files is blocked. The clips live in their own
// file to keep imessage.html small enough to preview.
//
//   npm run voice
//
// Re-run after re-recording any clip. File names must stay the same
// (rachel1.mp3, ovoa1.mp3, ...).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "..", "..");
const out = path.resolve(here, "..", "public", "voice-clips.js");

const names = fs
  .readdirSync(root)
  .filter((f) => /\.(mp3|m4a|wav|ogg)$/i.test(f))
  .sort();

if (names.length === 0) {
  console.error(`No audio files found in ${root}`);
  process.exit(1);
}

const mime = { mp3: "audio/mpeg", m4a: "audio/mp4", wav: "audio/wav", ogg: "audio/ogg" };
const entries = names.map((name) => {
  const ext = name.split(".").pop().toLowerCase();
  const b64 = fs.readFileSync(path.join(root, name)).toString("base64");
  return `  ${JSON.stringify(name)}: { type: ${JSON.stringify(mime[ext])}, data: "${b64}" },`;
});

fs.writeFileSync(
  out,
  `// Generated by scripts/build-voice-clips.mjs — do not edit.\nwindow.OVOA_CLIPS = {\n${entries.join("\n")}\n};\n`,
);
console.log(`Wrote ${names.length} clips to public/voice-clips.js: ${names.join(", ")}`);
